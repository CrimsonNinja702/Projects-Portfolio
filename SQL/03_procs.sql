-- Four small procedures. Three do one job each; the fourth runs them in order.
USE ROLE SYSADMIN;
USE WAREHOUSE ETL_WH;

-- 1. Copy raw rows into the history table (once per batch)
CREATE OR REPLACE PROCEDURE ETL_DEMO.ORDERS.SP_ARCHIVE_RAW()
RETURNS NUMBER
LANGUAGE SQL
AS
$$
BEGIN
  INSERT INTO ETL_DEMO.ORDERS.ORDERS_RAW_HISTORY
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, EMAIL, ORDER_DATE,
     PRODUCT, QUANTITY, UNIT_PRICE, STATUS, _BATCH_ID, _LOADED_AT)
  SELECT
    r.ORDER_ID, r.CUSTOMER_ID, r.CUSTOMER_NAME, r.EMAIL, r.ORDER_DATE,
    r.PRODUCT, r.QUANTITY, r.UNIT_PRICE, r.STATUS, r._BATCH_ID, r._LOADED_AT
  FROM ETL_DEMO.ORDERS.ORDERS_RAW r
  WHERE NOT EXISTS (                       -- skip a batch we already archived
    SELECT 1
    FROM ETL_DEMO.ORDERS.ORDERS_RAW_HISTORY h
    WHERE h._BATCH_ID = r._BATCH_ID
  );

  RETURN SQLROWCOUNT;
END;
$$;

-- 2. Save the bad rows, with the reason, in the rejected table
CREATE OR REPLACE PROCEDURE ETL_DEMO.ORDERS.SP_REJECT_BAD_ROWS()
RETURNS NUMBER
LANGUAGE SQL
AS
$$
BEGIN
  INSERT INTO ETL_DEMO.ORDERS.ORDERS_REJECTED
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, EMAIL, ORDER_DATE,
     PRODUCT, QUANTITY, UNIT_PRICE, STATUS, SOURCE_BATCH_ID, REJECT_REASON)
  SELECT
    c.ORDER_ID, c.CUSTOMER_ID, c.CUSTOMER_NAME, c.EMAIL, c.ORDER_DATE,
    c.PRODUCT, c.QUANTITY, c.UNIT_PRICE, c.STATUS, c._BATCH_ID, c.REJECT_REASON
  FROM ETL_DEMO.ORDERS.VW_ORDERS_RAW_CHECKED c
  WHERE c.REJECT_REASON IS NOT NULL
    AND NOT EXISTS (                       -- do not reject the same row twice
      SELECT 1
      FROM ETL_DEMO.ORDERS.ORDERS_REJECTED x
      WHERE x.SOURCE_BATCH_ID = c._BATCH_ID
        AND x.ORDER_ID = c.ORDER_ID
    );

  RETURN SQLROWCOUNT;
END;
$$;


-- 3. Load the clean rows into the final table, stamped with a load date
CREATE OR REPLACE PROCEDURE ETL_DEMO.ORDERS.SP_LOAD_FINAL(P_LOAD_DATE DATE)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
BEGIN
  INSERT INTO ETL_DEMO.ORDERS.ORDERS_FINAL
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, EMAIL, ORDER_DATE, PRODUCT,
     PRODUCT_CATEGORY, QUANTITY, UNIT_PRICE, LINE_TOTAL, STATUS, LOAD_DATE)
  SELECT
    UPPER(TRIM(c.ORDER_ID)),
    UPPER(TRIM(c.CUSTOMER_ID)),
    INITCAP(TRIM(c.CUSTOMER_NAME)),
    LOWER(TRIM(c.EMAIL)),
    TRY_TO_DATE(c.ORDER_DATE, 'YYYY-MM-DD'),
    INITCAP(TRIM(c.PRODUCT)),
    c.PRODUCT_CATEGORY,
    TRY_TO_NUMBER(c.QUANTITY),
    TRY_TO_DECIMAL(c.UNIT_PRICE, 12, 2),
    TRY_TO_NUMBER(c.QUANTITY) * TRY_TO_DECIMAL(c.UNIT_PRICE, 12, 2),
    CASE
      WHEN LOWER(TRIM(c.STATUS)) IN ('completed', 'shipped') THEN 'COMPLETE'
      WHEN LOWER(TRIM(c.STATUS)) = 'cancelled'               THEN 'CANCELLED'
      ELSE 'PENDING'
    END,
    :P_LOAD_DATE
  FROM ETL_DEMO.ORDERS.VW_ORDERS_RAW_CHECKED c
  WHERE c.REJECT_REASON IS NULL
    AND NOT EXISTS (                       -- already loaded for this load date?
      SELECT 1
      FROM ETL_DEMO.ORDERS.ORDERS_FINAL f
      WHERE f.ORDER_ID = UPPER(TRIM(c.ORDER_ID))
        AND f.LOAD_DATE = :P_LOAD_DATE
    )
  QUALIFY ROW_NUMBER() OVER (              -- same order twice in the batch? keep the latest
            PARTITION BY UPPER(TRIM(c.ORDER_ID))
            ORDER BY c._LOADED_AT DESC
          ) = 1;

  RETURN SQLROWCOUNT;
END;
$$;


-- 4. Run everything in order, empty the raw table, log the result
CREATE OR REPLACE PROCEDURE ETL_DEMO.ORDERS.SP_RUN_ORDERS_ETL(P_LOAD_DATE DATE)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  v_started  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();
  v_archived NUMBER DEFAULT 0;
  v_rejected NUMBER DEFAULT 0;
  v_loaded   NUMBER DEFAULT 0;
  v_err      VARCHAR;
BEGIN
  CALL ETL_DEMO.ORDERS.SP_ARCHIVE_RAW()               INTO :v_archived;
  CALL ETL_DEMO.ORDERS.SP_REJECT_BAD_ROWS()           INTO :v_rejected;
  CALL ETL_DEMO.ORDERS.SP_LOAD_FINAL(:P_LOAD_DATE)    INTO :v_loaded;

  -- Only empty the raw table once everything above has worked.
  TRUNCATE TABLE ETL_DEMO.ORDERS.ORDERS_RAW;

  INSERT INTO ETL_DEMO.ORDERS.ETL_RUN_LOG
    (RUN_ID, PROC_NAME, STATUS, ROWS_PROCESSED, ROWS_REJECTED, STARTED_AT, ENDED_AT)
  SELECT UUID_STRING(), 'SP_RUN_ORDERS_ETL', 'SUCCESS',
         :v_loaded, :v_rejected, :v_started, CURRENT_TIMESTAMP();

  RETURN 'Archived: ' || v_archived || ', rejected: ' || v_rejected || ', loaded: ' || v_loaded;

EXCEPTION
  WHEN OTHER THEN
    v_err := SQLERRM;
    INSERT INTO ETL_DEMO.ORDERS.ETL_RUN_LOG
      (RUN_ID, PROC_NAME, STATUS, ERROR_MESSAGE, STARTED_AT, ENDED_AT)
    SELECT UUID_STRING(), 'SP_RUN_ORDERS_ETL', 'FAILED',
           :v_err, :v_started, CURRENT_TIMESTAMP();
    RAISE;   -- raise the error again so a failed run is visible
END;
$$;